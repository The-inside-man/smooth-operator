import { chromium } from 'playwright';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts/ui', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 960 } });
const page = await context.newPage(); const errors = []; const external = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:4317') && !r.url().startsWith('data:')) external.push(r.url()); });
await page.goto('http://127.0.0.1:4317');
await page.getByText('TIM CONNECTED', { exact: true }).waitFor();
await page.screenshot({ path: 'artifacts/ui/workspace.png' });
await page.getByRole('button', { name: 'Browse model library' }).click();
await page.getByRole('dialog', { name: 'Model library' }).waitFor();
await page.screenshot({ path: 'artifacts/ui/library.png' });
const count = await page.locator('.model-card').count(); if (count < 1) throw new Error('No models discovered');
await page.getByLabel('Search models').fill('DreamShaper');
if (await page.locator('.model-card').count() !== 1) throw new Error('Model search failed');
await page.getByRole('button', { name: 'Use model' }).click();
if (await page.getByLabel('Select model').inputValue() === '') throw new Error('Model selection failed');
await page.getByRole('button', { name: 'Generation controls', exact: true }).click();
await page.getByRole('button', { name: 'Close generation settings' }).click();
await page.getByRole('button', { name: 'Settings', exact: true }).click();
await page.getByRole('dialog', { name: 'Settings' }).waitFor();
await page.screenshot({ path: 'artifacts/ui/settings.png' });
await page.keyboard.press('Escape');
await page.setViewportSize({ width: 1024, height: 768 });
await page.screenshot({ path: 'artifacts/ui/compact.png' });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
if (overflow) throw new Error('Horizontal overflow at 1024px');
if (errors.length || external.length) throw new Error(JSON.stringify({ errors, external }));
console.log(JSON.stringify({ models: count, consoleErrors: errors, externalRequests: external, compactOverflow: overflow }));
await browser.close();
